/**
 * Calculates the power of a number (base^exponent).
 * Calcola la potenza di un numero (base^esponente).
 * 
 * @param {number} base - The base / La base
 * @param {number} exponent - The exponent / L'esponente
 * @returns {number} The result of the power operation / Il risultato dell'operazione di potenza
 */
function power(base, exponent) {
    return Math.pow(base, exponent);
}

export { power };
