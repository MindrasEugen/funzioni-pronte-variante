/**
 * Returns the sign of a number: 1 for positive, -1 for negative, 0 for zero.
 * Restituisce il segno di un numero: 1 per positivo, -1 per negativo, 0 per zero.
 * 
 * @param {number} num - The number / Il numero
 * @returns {number} The sign: 1, -1, or 0 / Il segno: 1, -1, o 0
 */
function sign(num) {
    return Math.sign(num);
}

export { sign };
