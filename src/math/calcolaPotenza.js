/**
 * Calcola la potenza di un numero (base^esponente).
 * 
 * @param {number} base - La base
 * @param {number} esponente - L'esponente
 * @returns {number} Il risultato della potenza
 */
function calcolaPotenza(base, esponente) {
    return Math.pow(base, esponente);
}

export { calcolaPotenza };
